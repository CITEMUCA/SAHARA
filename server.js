const now = () => new Date().toISOString();
const hashIp = (ip) => crypto.createHash("sha256").update(String(ip) + "sic2026").digest("hex").slice(0, 16);

function str(v, max = 500) {
  if (typeof v !== "string") return "";
  return v.replace(/\u0000/g, "").trim().slice(0, max);
}

function isEmail(v) {
  return /^[^\s@]{1,64}@[^\s@]{1,190}\.[^\s@]{2,}$/.test(v);
}

function isPhone(v) {
  return /^\+?[0-9 ().-]{8,20}$/.test(v);
}

function isUrl(v) {
  try {
    const u = new URL(v);
    return u.protocol === "https:" || u.protocol === "http:";
  } catch {
    return false;
  }
}

function makeRef() {
  const n = crypto.randomInt(0, 36 ** 5).toString(36).toUpperCase().padStart(5, "0");
  return `SIC26-${n}`;
}

function parseJsonField(v, fallback) {
  if (typeof v !== "string" || !v) return fallback;
  try {
    return JSON.parse(v);
  } catch {
    return fallback;
  }
}

function asArray(v) {
  if (Array.isArray(v)) return v;
  if (typeof v === "string" && v) return [v];
  return [];
}

/** Limiteur de débit en mémoire (fenêtre glissante simple). */
function rateLimit({ windowMs, max }) {
  const hits = new Map();
  setInterval(() => {
    const t = Date.now();
    for (const [k, arr] of hits) {
      const kept = arr.filter((x) => t - x < windowMs);
      if (kept.length) hits.set(k, kept);
      else hits.delete(k);
    }
  }, windowMs).unref();
  return async (req, res, next) => {
    const t = Date.now();
    const arr = (hits.get(req.ip) || []).filter((x) => t - x < windowMs);
    if (arr.length >= max) {
      return res.status(429).json({ ok: false, error: "rate_limited" });
    }
    arr.push(t);
    hits.set(req.ip, arr);
    next();
  };
}

