function juryAverage(arr) {
  if (!Array.isArray(arr) || arr.length !== CRITERIA.length) return null;
  if (arr.some((n) => !Number.isInteger(n) || n < 1 || n > 5)) return null;
  return arr.reduce((a, b) => a + b, 0) / arr.length;
}

function hashPassword(password) {
  const salt = crypto.randomBytes(16).toString("hex");
  return `${salt}:${crypto.scryptSync(password, salt, 32).toString("hex")}`;
}

function checkPassword(password, stored) {
  if (!stored || !stored.includes(":")) return false;
  const [salt, hash] = stored.split(":");
  const got = crypto.scryptSync(String(password), salt, 32);
  const ref = Buffer.from(hash, "hex");
  return got.length === ref.length && crypto.timingSafeEqual(got, ref);
}

function decodeName(name) {
  if (!name || !/[ÃÂâ€]/.test(name)) return name || "";
  const fixed = Buffer.from(name, "latin1").toString("utf8");
  return fixed.includes("\uFFFD") ? name : fixed;
}

async function averagesByRegistration() {
  const groups = new Map();
  const rows = await db
    .prepare(
      `SELECT s.registration_id, s.scores
       FROM scores s
       JOIN jurors j ON j.id = s.juror_id
       JOIN registrations r ON r.id = s.registration_id
       WHERE j.track = r.track`
    )
    .all();
  for (const row of rows) {
    let parsed;
    try {
      parsed = JSON.parse(row.scores);
    } catch {
      continue;
    }
    const avg = juryAverage(parsed);
    if (avg == null) continue;
    const list = groups.get(row.registration_id) || [];
    list.push(avg);
    groups.set(row.registration_id, list);
  }
  const out = new Map();
  for (const [id, avgs] of groups) {
    out.set(id, {
      avg: Math.round((avgs.reduce((a, b) => a + b, 0) / avgs.length) * 10) / 10,
      n: avgs.length,
    });
  }
  return out;
}

