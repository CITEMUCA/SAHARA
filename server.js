function validateRegistration(body, file) {
  const errors = {};
  const req = (key, val, ok = Boolean(val)) => {
    if (!ok) errors[key] = "invalid";
  };

  const leader = {
    first_name: str(body.first_name, 80),
    last_name: str(body.last_name, 80),
    email: str(body.email, 200).toLowerCase(),
    phone: str(body.phone, 30),
    gender: str(body.gender, 20),
    city: str(body.city, 80),
    profile: str(body.profile, 30),
    institution: str(body.institution, 200),
    position: str(body.position, 120),
    linkedin: str(body.linkedin, 300),
  };
  req("first_name", leader.first_name);
  req("last_name", leader.last_name);
  req("email", leader.email, isEmail(leader.email));
  req("phone", leader.phone, isPhone(leader.phone));
  req("city", leader.city);
  req("institution", leader.institution);
  const PROFILES = ["researcher", "student", "startup"];
  req("profile", leader.profile, PROFILES.includes(leader.profile));
  leader.study_level = str(body.study_level, 20);
  leader.training_title = str(body.training_title, 160);
  if (leader.profile === "student") {
    req("study_level", leader.study_level, ["master", "doctorate", "engineer"].includes(leader.study_level));
    req("training_title", leader.training_title, leader.training_title.length >= 2);
  }
  if (leader.linkedin) req("linkedin", leader.linkedin, isUrl(leader.linkedin));

  const teamSize = Number.parseInt(body.team_size, 10) || 1;
  const members = parseJsonField(body.members, [])
    .slice(0, 4)
    .map((m) => ({
      name: str(m && m.name, 120),
      email: str(m && m.email, 200).toLowerCase(),
      role: str(m && m.role, 120),
      institution: str(m && m.institution, 200),
      profile: str(m && m.profile, 20),
      study_level: str(m && m.study_level, 20),
      training_title: str(m && m.training_title, 160),
    }))
    .filter((m) => m.name);
  req("team_size", teamSize, teamSize >= 1 && teamSize <= 5);
  members.forEach((m, i) => {
    if (m.email && !isEmail(m.email)) errors[`member_${i}_email`] = "invalid";
  });

  const project = {
    team_name: str(body.team_name, 120),
    team_acronym: str(body.team_acronym, 30),
    track: str(body.track, 10),
    challenge: Number.parseInt(body.challenge, 10),
    title: str(body.title, 150),
    acronym: str(body.acronym, 30),
    summary: str(body.summary, 6000),
    problem: str(body.problem, 1500),
    solution: str(body.solution, 1500),
    innovation: str(body.innovation, 1200),
    target: str(body.target, 800),
    impact: str(body.impact, 1200),
    territories: asArray(parseJsonField(body.territories, [])).filter((t) => TERRITORIES.includes(t)),
    maturity: str(body.maturity, 20),
    trl: body.trl ? Number.parseInt(body.trl, 10) : null,
    ip_status: str(body.ip_status, 30),
    startup_name: str(body.startup_name, 150),
    startup_year: str(body.startup_year, 4),
    startup_legal: str(body.startup_legal, 60),
    website: str(body.project_website, 300),
    video_url: str(body.video_url, 300),
    needs: asArray(parseJsonField(body.needs, [])).filter((n) => NEEDS.includes(n)),
    heard_from: str(body.heard_from, 60),
  };
  req("track", project.track, TRACKS.includes(project.track));
  req("challenge", project.challenge, CHALLENGES.includes(project.challenge));
  req("title", project.title, project.title.length >= 3);
  const summaryWords = project.summary.trim() ? project.summary.trim().split(/\s+/).length : 0;
  req("summary", project.summary, project.summary.length >= 40 && summaryWords <= 700);
  if (project.video_url) req("video_url", project.video_url, isUrl(project.video_url));
  if (project.website) req("project_website", project.website, isUrl(project.website));

  const consents = {
    rules: body.consent_rules === "true" || body.consent_rules === "on",
    data: body.consent_data === "true" || body.consent_data === "on",
    media: body.consent_media === "true" || body.consent_media === "on",
  };
  req("consent_rules", consents.rules);
  req("consent_data", consents.data);
  req("consent_media", consents.media);

  return { errors, leader, members, teamSize, project, consents };
}

