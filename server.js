async function buildWorkbook(allRows, { track, challenge } = {}) {
  const wb = new ExcelJS.Workbook();
  wb.creator = "Moroccan Sahara Innovation Challenge 2026";
  wb.created = new Date();

  const filtered = allRows.filter((r) => {
    if (track && r.track !== track) return false;
    if (challenge && Number(r.challenge) !== Number(challenge)) return false;
    return true;
  });

  if (track || challenge) {
    const bits = [];
    if (track) bits.push(`Parcours ${track.toUpperCase()}`);
    if (challenge) bits.push(`Challenge ${challenge} — ${CHALLENGE_TITLES[challenge] || ""}`);
    const name = bits.join(" · ").slice(0, 28) || "Export";
    fillSheet(wb.addWorksheet(name), filtered, bits.join(" · ") || "Export filtré");
    return wb;
  }

  fillSheet(wb.addWorksheet("Toutes"), allRows, "Toutes les candidatures");
  for (const t of TRACKS) {
    fillSheet(wb.addWorksheet(t.toUpperCase()), allRows.filter((r) => r.track === t), `Parcours ${t.toUpperCase()}`);
  }
  for (const n of CHALLENGES) {
    const short = `C${n}`;
    fillSheet(
      wb.addWorksheet(short),
      allRows.filter((r) => Number(r.challenge) === n),
      `Challenge ${n} — ${CHALLENGE_TITLES[n]}`
    );
  }
  return wb;
}

app.get("/api/admin/export.xlsx", requireAdmin, async (req, res) => {
  const track = str(req.query.track, 10).toLowerCase();
  const challenge = Number(req.query.challenge);
  const useTrack = TRACKS.includes(track) ? track : "";
  const useChallenge = CHALLENGES.includes(challenge) ? challenge : null;
  const rows = await db.prepare("SELECT * FROM registrations ORDER BY track ASC, challenge ASC, created_at ASC").all();
  const wb = await buildWorkbook(rows, { track: useTrack, challenge: useChallenge });
  const parts = ["sic2026"];
  if (useTrack) parts.push(useTrack.toUpperCase());
  if (useChallenge) parts.push(`challenge-${String(useChallenge).padStart(2, "0")}`);
  if (parts.length === 1) parts.push("candidatures");
  const filename = `${parts.join("-")}.xlsx`;
  res.setHeader("Content-Type", "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet");
  res.setHeader("Content-Disposition", `attachment; filename="${filename}"`);
  await wb.xlsx.write(res);
  res.end();
});

