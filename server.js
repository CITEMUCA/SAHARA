function toPg(sql) {
  let n = 0;
  return String(sql).replace(/COLLATE NOCASE/gi, "").replace(/\?/g, () => `$${++n}`);
}

const db = {
  async exec(sql) {
    await pool.query(sql);
  },
  prepare(sql) {
    return {
      async get(...params) {
        const r = await pool.query(toPg(sql), params);
        return r.rows[0];
      },
      async all(...params) {
        const r = await pool.query(toPg(sql), params);
        return r.rows;
      },
      async run(...params) {
        let text = toPg(sql);
        if (/^\s*insert\s+/i.test(sql) && !/returning\b/i.test(sql)) text += " RETURNING id";
        const r = await pool.query(text, params);
        return { lastInsertRowid: r.rows[0] && r.rows[0].id, changes: r.rowCount };
      },
    };
  },
};

